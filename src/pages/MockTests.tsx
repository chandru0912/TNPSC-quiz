const formatCountdown = (seconds: number) => {
  const s = Math.max(0, Math.floor(seconds))
  const hrs = Math.floor(s / 3600)
  const mins = Math.floor((s % 3600) / 60)
  const secs = s % 60
  return [hrs, mins, secs].map((v) => String(v).padStart(2, '0')).join(':')
}

const isTechnicalGeneratorDescription = (desc?: string | null): boolean => {
  if (!desc || !desc.trim()) return true
  return /created from question bank|generated via mock test mcq generator|auto-generated|generated by mock test/i.test(
    desc
  )
}

const formatStudentTestTitle = (
  test: PublishedMockTest,
  fallbackUnitTitle?: string
): string => {
  if (test.testCategory === 'lesson_wise' && test.lesson && test.lesson.trim()) {
    return test.lesson.trim()
  }

  let cleaned = String(test.title || '').trim()
  // Strip technical prefixes like "TNPSC Group 1 — 6th Std Unit 1: "
  cleaned = cleaned
    .replace(/^TNPSC\s+Group\s+[\w\s&/]+?\s*[—–\-:]\s*/i, '')
    .replace(/^\d+(?:st|nd|rd|th)\s*(?:Std|Standard)\s*[—–\-:]?\s*/i, '')

  if (test.testCategory === 'lesson_wise' || test.testCategory === 'unit_wise') {
    cleaned = cleaned.replace(/^Unit\s+[IVX0-9]+\s*[—–\-:]\s*/i, '')
  }

  cleaned = cleaned.replace(/\s+(?:Lesson-wise|Unit-wise)\s+Test$/i, '').replace(/\s+Test$/i, '').trim()

  if (cleaned) return cleaned
  if (test.testCategory === 'unit_wise' && fallbackUnitTitle) return fallbackUnitTitle
  return String(test.title || 'Mock Test').trim()
}

const matchesGroup = (test: PublishedMockTest, selectedGroup: TnpscGroupTab): boolean => {
  const grp = `${test.category || ''} ${test.tnpscGroup || ''}`.toLowerCase()
  if (selectedGroup === 'group1') return grp.includes('group1') || grp.includes('group 1')
  if (selectedGroup === 'group2_2a') return grp.includes('group2') || grp.includes('group 2')
  if (selectedGroup === 'group4') return grp.includes('group4') || grp.includes('group 4') || grp.includes('vao')
  return false
}

const mapGroupToRegistryKey = (grp: TnpscGroupTab): 'group1' | 'group2' | 'group4' => {
  if (grp === 'group2_2a') return 'group2'
  if (grp === 'group4') return 'group4'
  return 'group1'
}

const parseStdNum = (std?: string | null): number | null => {
  if (!std) return null
  const m = String(std).match(/\d+/)
  return m ? Number(m[0]) : null
}

function calculateSafeProgress(completed: number, available: number): number {
  if (!Number.isFinite(available) || available <= 0) return 0
  const safeCompleted = Math.max(0, Math.min(completed, available))
  return Math.round((safeCompleted / available) * 100)
}

